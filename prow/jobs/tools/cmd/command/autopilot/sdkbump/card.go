const (
	bodyMarker           = "<!-- autopilot:sdk-bump v1 -->"
	sectionServerDefault = "server-default"
	sectionGate          = "gate-verdict"
	// GitHub's limit is 65536 characters; stay well below it.
	maxBodyBytes    = 60000
	maxCRDRows      = 40
	maxFindingRows  = 30
	crdCompatSchema = "ack.crd-compat/v1"
)

// CRDDoc is the part of Plan 4's ack.crd-compat/v1 document the card shows.
// dod reads the same bytes with its own, stricter parser.
type CRDDoc struct {
	Schema  string `json:"schema"`
	BaseRef string `json:"base_ref"`
	// HeadRef is not written by Plan 4; dod requires it on a document given
	// as a file (CRDCompatJSON) and checks it names this run's head.
	HeadRef             string                 `json:"head_ref,omitempty"`
	Breaking            bool                   `json:"breaking"`
	Buckets             map[string][]CRDChange `json:"buckets"`
	SensitiveCandidates []CRDField             `json:"sensitive_candidates"`
}

type CRDChange struct {
	File       string `json:"file"`
	Kind       string `json:"kind"`
	Bucket     string `json:"bucket"`
	Field      string `json:"field"`
	ChangeType string `json:"change_type"`
	Breaking   bool   `json:"breaking"`
}

type CRDField struct {
	File  string `json:"file"`
	Kind  string `json:"kind"`
	Field string `json:"field"`
}

// ParseCRDDoc decodes a crd-compat-check --output json document.
func ParseCRDDoc(b []byte) (*CRDDoc, error) {
	var d CRDDoc
	if err := json.Unmarshal(b, &d); err != nil {
		return nil, err
	}
	if d.Schema != crdCompatSchema {
		return nil, fmt.Errorf("crd-compat document schema %q, want %s", d.Schema, crdCompatSchema)
	}
	return &d, nil
}

// CardInput is everything the review card shows. After holds the pins at the
// bump commit.
type CardInput struct {
	Service         string
	Target          Target
	Before, After   Pins
	CRD             *CRDDoc
	Deps            Dependents
	JobName, JobURL string
}

var cellReplacer = strings.NewReplacer("|", `\|`, "\r", " ", "\n", " ", "`", "'", "<", "&lt;", ">", "&gt;")

// code renders a value as inline code that cannot end a cell or forge markup.
func code(s string) string {
	if s == "" {
		return "(none)"
	}
	return "`" + cellReplacer.Replace(s) + "`"
}

func codes(s []string) string {
	if len(s) == 0 {
		return "none"
	}
	out := make([]string, len(s))
	for i, v := range s {
		out[i] = code(v)
	}
	return strings.Join(out, ", ")
}

func sectionBegin(name string) string { return "<!-- autopilot:" + name + ":begin -->" }
func sectionEnd(name string) string   { return "<!-- autopilot:" + name + ":end -->" }

func section(name, content string) string {
	return sectionBegin(name) + "\n" + content + sectionEnd(name) + "\n"
}

// ReplaceSection swaps the content of the one named section; false when the
// markers are missing, repeated or out of order (a human edited them).
func ReplaceSection(body, name, content string) (string, bool) {
	b, e := sectionBegin(name), sectionEnd(name)
	if strings.Count(body, b) != 1 || strings.Count(body, e) != 1 {
		return body, false
	}
	i := strings.Index(body, b) + len(b)
	j := strings.Index(body, e)
	if j < i {
		return body, false
	}
	return body[:i] + "\n" + content + body[j:], true
}

// Title is the PR title.
func Title(t Target) string { return "Update aws-sdk-go-v2/service/" + t.Package + " to " + t.Version }

func short(h string) string {
	if len(h) > 12 {
		return h[:12]
	}
	return h
}

// commitMessage is the bump commit's message; its last paragraph is the
// Plan 3 trailer block Plan 5's provenance check reads.
func commitMessage(workItem string, t Target, p Pins) string {
	var b strings.Builder
	b.WriteString(Title(t) + "\n\n")
	fmt.Fprintf(&b, "Regenerated by ACK Autopilot (%s, no LLM) with code-generator %s (%s)\n"+
		"and runtime %s, the versions this controller was last generated with.\n\n",
		Workflow, p.CodegenVersion, short(p.CodegenHash), p.RuntimeVersion)
	b.WriteString("Producer: " + Producer + "\n")
	if workItem != "" {
		b.WriteString("Work-Item: " + workItem + "\n")
	}
	b.WriteString("Change-Class: " + dod.ClassSDKBump)
	return b.String()
}

// RenderCard is the PR body above the gate section: what dod scans as the
// PR body.
func RenderCard(in CardInput) string {
	var b strings.Builder
	b.WriteString(bodyMarker + "\n")
	fmt.Fprintf(&b, "## ACK Autopilot: SDK bump for %s\n\n", code(in.Service))
	b.WriteString("**Class:** SDK-bump (regenerate only). **Level:** human-merge: in Phases 1–4 a person merges every autopilot PR.\n")
	fmt.Fprintf(&b, "**Why:** the API-change detector found a newer %s model; this PR moves the controller to %s and regenerates it. No LLM was used.\n\n",
		code(in.Target.Package), code("service/"+in.Target.Package+"/"+in.Target.Version))

	b.WriteString("### What you must judge\n\n")
	for _, j := range judgements(in) {
		b.WriteString("- " + j + "\n")
	}

	b.WriteString("\n### Server-default fields (the merge is blocked until each is decided)\n\n")
	b.WriteString(section(sectionServerDefault, RenderDependents(in.Deps)))

	b.WriteString("\n### CRD API delta\n\n")
	b.WriteString(renderCRD(in.CRD, in.Deps))

	b.WriteString("\n### Evidence\n\n| pin | before | after |\n|---|---|---|\n")
	for _, r := range []struct{ name, before, after string }{
		{"aws_sdk_go_version", in.Before.CoreSDK, in.After.CoreSDK},
		{"aws_service_sdk_version", in.Before.ServiceSDK, in.After.ServiceSDK},
		{"go.mod " + sdkServicePrefix + in.Target.Package, in.Before.GoModService, in.After.GoModService},
		{"go.mod " + sdkCoreModule, in.Before.GoModCore, in.After.GoModCore},
		{"go.mod " + smithyModule, in.Before.GoModSmithy, in.After.GoModSmithy},
	} {
		fmt.Fprintf(&b, "| %s | %s | %s |\n", code(r.name), code(r.before), code(r.after))
	}
	fmt.Fprintf(&b, "\nRegenerated with code-generator %s (%s) and runtime %s, the versions this controller was last generated with.\n",
		code(in.Before.CodegenVersion), code(short(in.Before.CodegenHash)), code(in.Before.RuntimeVersion))
	if in.JobName != "" {
		job := code(in.JobName)
		if strings.HasPrefix(in.JobURL, "https://") {
			job = "[" + job + "](" + strings.NewReplacer("(", "%28", ")", "%29", " ", "%20").Replace(in.JobURL) + ")"
		}
		b.WriteString("Run: " + job + ".\n")
	}

	b.WriteString("\n### Cost\n\nLLM tokens: 0. Real-AWS e2e runs: 0 (this workflow runs none; see \"Not covered\" below).\n")
	return b.String()
}

// judgements are the card's "What you must judge" bullets, at most three.
func judgements(in CardInput) []string {
	var j []string
	add := func(s string) {
		if len(j) < 3 {
			j = append(j, s)
		}
	}
	switch {
	case !in.Deps.Known:
		add("The server-default dependents could not be read from the ledger, so the merge stays blocked (`autopilot/server-default` fails) until a run can read them.")
	case in.Deps.Unresolved() > 0:
		add(fmt.Sprintf("Decide `late_initialize`, `compare.is_ignored` or \"no server default\" for %d new Spec field(s) "+
			"a read returns (checklist below). Without a decision every existing resource shows a Spec delta after the upgrade.",
			in.Deps.Unresolved()))
	}
	for _, m := range []struct{ name, from, to string }{
		{sdkCoreModule, in.Before.GoModCore, in.After.GoModCore},
		{smithyModule, in.Before.GoModSmithy, in.After.GoModSmithy},
	} {
		if m.from != m.to {
			add(fmt.Sprintf("%s moved %s → %s with this bump: client behaviour (retries, checksums, endpoint rules) can change, and the CRD diff cannot show it.",
				code(m.name), code(m.from), code(m.to)))
		}
	}
	if in.Before.ServiceSDK == "" {
		add(fmt.Sprintf("The controller moves from the core SDK pin %s to the per-service pin %s; later bumps compare against the per-service tag.",
			code(in.Before.CoreSDK), code(in.Target.Version)))
	}
	if in.CRD != nil {
		if n := len(in.CRD.Buckets["added_optional_spec"]) + len(in.CRD.Buckets["added_status"]); n > 0 {
			add(fmt.Sprintf("%d new field(s) arrive with this bump (table below): a bump regenerates every new member, not only the detector's findings.", n))
		}
	}
	if len(j) == 0 {
		add("Nothing beyond the gate verdict below.")
	}
	return j
}

// RenderDependents is the content of the server-default section.
func RenderDependents(d Dependents) string {
	var b strings.Builder
	switch {
	case !d.Known:
		b.WriteString("Unknown: this run could not read the ledger, so it cannot tell which new fields need a decision. The merge stays blocked until a run that can read it.\n")
		return b.String()
	case len(d.Items) == 0:
		b.WriteString("None. No field in this bump is a server-default dependent.\n")
		return b.String()
	}
	for _, x := range d.Items {
		if x.Resolved {
			fmt.Fprintf(&b, "- [x] %s %s (%s): %s\n", code(x.Resource), code(x.FieldPath), code(x.KeyHash), cellReplacer.Replace(x.How))
			continue
		}
		fmt.Fprintf(&b, "- [ ] %s %s (%s, ledger state %s): add `late_initialize` or `compare.is_ignored` for it to generator.yaml "+
			"as a commit on this branch, or, if it has no server default, comment `/autopilot wontfix %s` on its api-change issue.\n",
			code(x.Resource), code(x.FieldPath), code(x.KeyHash), code(string(x.State)), cellReplacer.Replace(x.KeyHash))
	}
	b.WriteString("\nThe boxes come from the ledger and from generator.yaml on this branch; ticking them by hand changes nothing.\n")
	return b.String()
}

func isDependent(d Dependents, kind, field string) bool {
	for _, x := range d.Items {
		if strings.EqualFold(x.Resource, kind) && strings.EqualFold("spec."+x.FieldPath, field) {
			return true
		}
	}
	return false
}

func renderCRD(doc *CRDDoc, deps Dependents) string {
	if doc == nil {
		return "Not available: `crd-compat-check` did not produce an `ack.crd-compat/v1` document, so the `crd-diff` gate cannot pass.\n"
	}
	var names []string
	for n, cs := range doc.Buckets {
		if len(cs) > 0 {
			names = append(names, n)
		}
	}
	sort.Strings(names)
	if len(names) == 0 {
		return "No CRD schema changes.\n"
	}
	var b strings.Builder
	b.WriteString("| bucket | changes |\n|---|---|\n")
	for _, n := range names {
		fmt.Fprintf(&b, "| %s | %d |\n", code(n), len(doc.Buckets[n]))
	}
	rows := append(append([]CRDChange{}, doc.Buckets["added_optional_spec"]...), doc.Buckets["added_status"]...)
	sort.Slice(rows, func(i, j int) bool {
		if rows[i].Kind != rows[j].Kind {
			return rows[i].Kind < rows[j].Kind
		}
		return rows[i].Field < rows[j].Field
	})
	if len(rows) > 0 {
		b.WriteString("\n| kind | field | bucket | server-default |\n|---|---|---|---|\n")
		for i, r := range rows {
			if i == maxCRDRows {
				fmt.Fprintf(&b, "\n… and %d more added field(s); the full list is in `crd-compat.json` in the run's artifacts.\n", len(rows)-maxCRDRows)
				break
			}
			sd := "no"
			if isDependent(deps, r.Kind, r.Field) {
				sd = "yes"
			}
			fmt.Fprintf(&b, "| %s | %s | %s | %s |\n", code(r.Kind), code(r.Field), code(r.Bucket), sd)
		}
	}
	if doc.Breaking {
		b.WriteString("\n**Breaking:** crd-compat-check reports a breaking change; see the gate verdict.\n")
	}
	if len(doc.SensitiveCandidates) > 0 {
		var fs []string
		for _, c := range doc.SensitiveCandidates {
			fs = append(fs, code(c.Kind)+" "+code(c.Field))
		}
		sort.Strings(fs)
		b.WriteString("\n**Field names that suggest a secret:** " + strings.Join(fs, ", ") + "\n")
	}
	return b.String()
}

// RenderGateSection is the verdict summary between the gate markers.
func RenderGateSection(v *dod.Verdict, digest string) string {
	var b strings.Builder
	b.WriteString("### Gate verdict (ack-dod)\n\n")
	reclass := "none"
	if v.ReclassifyTo != "" {
		reclass = code(v.ReclassifyTo)
	}
	fmt.Fprintf(&b, "**Verdict:** %s. **Reclassify to:** %s. **Human commits:** %d. **Digest:** %s\n\n",
		code(string(v.Verdict)), reclass, v.HumanCommits, code(digest))
	if len(v.Reasons) > 0 {
		b.WriteString("**Reasons:** " + codes(v.Reasons) + "\n\n")
	}
	b.WriteString("| check | binding | status | reasons |\n|---|---|---|---|\n")
	for _, c := range v.Checks {
		binding := "no"
		if c.Binding {
			binding = "yes"
		}
		fmt.Fprintf(&b, "| %s | %s | %s | %s |\n", code(c.ID), binding, code(string(c.Status)), codes(c.Reasons))
	}
	var notable []string
	for _, c := range v.Checks {
		for _, f := range c.Findings {
			if !f.Fails && !strings.HasPrefix(f.Signature, "CRD_NEEDS_JUDGEMENT") && !strings.HasPrefix(f.Signature, "SENSITIVE") {
				continue
			}
			line := "- " + code(f.Signature) + " (" + code(c.ID) + ")"
			if f.File != "" {
				line += " in " + code(f.File)
			}
			if f.Detail != "" {
				line += ": " + cellReplacer.Replace(f.Detail)
			}
			notable = append(notable, line)
		}
	}
	if len(notable) > 0 {
		b.WriteString("\n**Findings to read** (the failing ones, and the ones that need judgement):\n\n")
		for i, l := range notable {
			if i == maxFindingRows {
				fmt.Fprintf(&b, "- … and %d more in `verdict.json`.\n", len(notable)-maxFindingRows)
				break
			}
			b.WriteString(l + "\n")
		}
	}
	if len(v.NotCovered) > 0 {
		b.WriteString("\n**Not covered by these gates:** " + codes(v.NotCovered) + ". A person judges these.\n")
	}
	b.WriteString("\nThe verdict document is `verdict.json` in this run's artifacts; `Gate-Verdict` below is its SHA-256, " +
		"which `ack-build-tools autopilot verify-verdict` checks against this PR's head.\n")
	return section(sectionGate, b.String())
}

// Trailers is the PR body's last paragraph (it survives Tide's squash).
func Trailers(workItem, digest string) string {
	var b strings.Builder
	b.WriteString("Producer: " + Producer + "\n")
	if workItem != "" {
		b.WriteString("Work-Item: " + workItem + "\n")
	}
	b.WriteString("Change-Class: " + dod.ClassSDKBump + "\n")
	b.WriteString(dod.TrailerKey + ": " + digest + "\n")
	return b.String()
}

// ComposeBody joins the parts with blank lines, so the trailers stay the last
// paragraph.
func ComposeBody(card, gate, trailers string) string { return card + "\n" + gate + "\n" + trailers }

var trailerLineRE = regexp.MustCompile(`^([A-Za-z0-9][A-Za-z0-9-]*):[ \t]*(.*?)[ \t]*$`)

// trailerValue is the last value of key in text's last paragraph, when every
// line of that paragraph is a trailer.
func trailerValue(text, key string) (string, bool) {
	paras := strings.Split(strings.TrimSpace(strings.ReplaceAll(text, "\r\n", "\n")), "\n\n")
	val, ok := "", false
	for _, l := range strings.Split(paras[len(paras)-1], "\n") {
		m := trailerLineRE.FindStringSubmatch(l)
		if m == nil {
			return "", false
		}
		if strings.EqualFold(m[1], key) {
			val, ok = m[2], true
		}
	}
	return val, ok
}
