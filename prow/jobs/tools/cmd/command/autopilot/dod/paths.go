package dod

import (
	"path"
	"regexp"
	"strings"
)

// regenHeader marks a file regen-clean must reproduce. ATTRIBUTION.md
// (attribution-gen) and config/crd/common (copied from runtime) carry other
// headers and are covered by regenOutputs or depFiles instead.
var regenHeader = regexp.MustCompile(`(?m)^(//|#) Code generated by (ack-generate|controller-gen)\. DO NOT EDIT\.\s*$`)

const headerWindow = 4096

func hasRegenHeader(b []byte) bool {
	if len(b) > headerWindow {
		b = b[:headerWindow]
	}
	return regenHeader.Match(b)
}

// regenOutputs are paths make build-controller rewrites that carry no header.
var regenOutputs = []string{
	"apis/*/ack-generate-metadata.yaml", "apis/*/generator.yaml",
	"config/crd/bases/*.yaml", "config/crd/common/**", "config/crd/kustomization.yaml",
	"config/controller/kustomization.yaml",
	"config/rbac/cluster-role-controller.yaml", "config/rbac/role-reader.yaml", "config/rbac/role-writer.yaml",
	"helm/crds/*.yaml", "helm/templates/**", "helm/Chart.yaml", "helm/values.yaml", "helm/values.schema.json",
}

// headerDirs are where a regen header counts.
var headerDirs = []string{"apis/**", "cmd/**", "pkg/**"}

// sensitivePaths need a human and the sensitive-path label (design §6); no
// class allows them. Generated RBAC (regenOutputs) is excluded.
var sensitivePaths = []string{
	".github/**", "Makefile", "scripts/**", "OWNERS", "OWNERS_ALIASES", "config/rbac/**", "test/e2e/requirements.txt",
}

// generatedToken in a class's list stands for every generatedFile.
const generatedToken = "@generated"

var (
	sdkBumpPaths     = []string{"go.mod", "go.sum", "ATTRIBUTION.md", generatedToken}
	configOnlyPaths  = append(append([]string{}, sdkBumpPaths...), "generator.yaml", "test/e2e/**", "config/iam/**")
	handWrittenPaths = append(append([]string{}, configOnlyPaths...), "templates/**", "pkg/**")
)

// classPaths are the per-class path allowlists (design §6).
var classPaths = map[string][]string{
	ClassMechanical:  {"go.mod", "go.sum", "ATTRIBUTION.md", "Dockerfile"},
	ClassDocsOnly:    sdkBumpPaths,
	ClassSDKBump:     sdkBumpPaths,
	ClassConfigOnly:  configOnlyPaths,
	ClassHandWritten: handWrittenPaths,
	ClassNewResource: handWrittenPaths,
}

// gitConfigPaths change what git diff and git status show (diff attributes,
// ignore rules), so they are sensitive everywhere, even under a regen output.
var gitConfigPaths = []string{"**/.gitattributes", "**/.gitignore"}

// globMatch matches one slash-separated path: "dir/**" is everything under
// dir, "**/name" is name in any directory, otherwise path.Match, where *
// never crosses a slash.
func globMatch(pattern, name string) bool {
	if base, ok := strings.CutPrefix(pattern, "**/"); ok {
		ok, _ := path.Match(base, path.Base(name))
		return ok
	}
	if prefix, ok := strings.CutSuffix(pattern, "**"); ok && strings.HasSuffix(prefix, "/") {
		return strings.HasPrefix(name, prefix)
	}
	ok, _ := path.Match(pattern, name)
	return ok
}

func matchAny(patterns []string, name string) bool {
	for _, p := range patterns {
		if globMatch(p, name) {
			return true
		}
	}
	return false
}

// generatedFile reports whether f is regeneration output. A header counts on
// both sides of a modified file (head only for an added one) and only under
// apis/, cmd/ or pkg/; regen-clean proves every such file is reproduced.
func generatedFile(f changedFile) bool {
	if matchAny(regenOutputs, f.Path) {
		return true
	}
	if !matchAny(headerDirs, f.Path) {
		return false
	}
	switch f.Status {
	case 'A':
		return hasRegenHeader(f.Head)
	case 'D':
		return hasRegenHeader(f.Base)
	default:
		return hasRegenHeader(f.Base) && hasRegenHeader(f.Head)
	}
}

func sensitivePath(p string) bool {
	return matchAny(gitConfigPaths, p) || (matchAny(sensitivePaths, p) && !matchAny(regenOutputs, p))
}

func allowedFor(class string, f changedFile) bool {
	if sensitivePath(f.Path) {
		return false
	}
	for _, p := range classPaths[class] {
		if p == generatedToken {
			if f.Generated {
				return true
			}
			continue
		}
		if globMatch(p, f.Path) {
			return true
		}
	}
	return false
}

// reclassifyLadder is searched for the first class that allows a path.
var reclassifyLadder = []string{ClassSDKBump, ClassConfigOnly, ClassHandWritten}

func checkPathAllowlist(class string, files []changedFile) Check {
	if len(files) == 0 {
		return newCheck(CheckPathAllowlist, []Finding{{Signature: "EMPTY_DIFF", Fails: true}})
	}
	var findings []Finding
	reclass, sensitive := "", false
	for _, f := range files {
		if allowedFor(class, f) {
			continue
		}
		sig := "PATH_NOT_ALLOWED"
		if sensitivePath(f.Path) {
			sig, sensitive = "SENSITIVE_PATH", true
		}
		findings = append(findings, Finding{Signature: sig, File: f.Path, Detail: "status " + string(f.Status), Fails: true})
		need := ClassHandWritten
		for _, c := range reclassifyLadder {
			if allowedFor(c, f) {
				need = c
				break
			}
		}
		reclass = atLeast(reclass, need)
	}
	c := newCheck(CheckPathAllowlist, findings)
	c.Reclassify = reclass
	if sensitive {
		c.Labels = []string{LabelSensitivePath}
	}
	return c
}
