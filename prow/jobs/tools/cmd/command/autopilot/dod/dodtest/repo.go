// Package dodtest builds throwaway git repositories for the dod tests. Commits
// use fixed identities and dates, and the user's git config is ignored.
package dodtest

import (
	"errors"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"testing"
)

const (
	Human = "human@example.com"
	Bot   = "bot@example.com"
	// GoHeader starts a file regen-clean must reproduce.
	GoHeader = "// Code generated by ack-generate. DO NOT EDIT.\n\n"
)

type Repo struct {
	t   testing.TB
	Dir string
}

func NewRepo(t testing.TB) *Repo {
	t.Helper()
	r := &Repo{t: t, Dir: t.TempDir()}
	r.Git("init", "--quiet", "--initial-branch=main")
	return r
}

func (r *Repo) env(email string) []string {
	return append(os.Environ(),
		"GIT_CONFIG_NOSYSTEM=1", "GIT_CONFIG_GLOBAL="+os.DevNull, "HOME="+r.Dir,
		"GIT_AUTHOR_NAME=test", "GIT_AUTHOR_EMAIL="+email,
		"GIT_COMMITTER_NAME=test", "GIT_COMMITTER_EMAIL="+email,
		"GIT_AUTHOR_DATE=2026-11-16T00:00:00Z", "GIT_COMMITTER_DATE=2026-11-16T00:00:00Z")
}

// Git runs git in the repo as Human and returns its trimmed stdout.
func (r *Repo) Git(args ...string) string { return r.gitAs(Human, args...) }

func (r *Repo) gitAs(email string, args ...string) string {
	r.t.Helper()
	cmd := exec.Command("git", append([]string{"-C", r.Dir}, args...)...)
	cmd.Env = r.env(email)
	out, err := cmd.Output()
	if err != nil {
		var ee *exec.ExitError
		stderr := ""
		if errors.As(err, &ee) {
			stderr = string(ee.Stderr)
		}
		r.t.Fatalf("git %s: %v: %s", strings.Join(args, " "), err, stderr)
	}
	return strings.TrimSpace(string(out))
}

func (r *Repo) Write(path, content string) {
	r.t.Helper()
	p := filepath.Join(r.Dir, filepath.FromSlash(path))
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		r.t.Fatal(err)
	}
	if err := os.WriteFile(p, []byte(content), 0o644); err != nil {
		r.t.Fatal(err)
	}
}

func (r *Repo) Remove(path string) {
	r.t.Helper()
	if err := os.Remove(filepath.Join(r.Dir, filepath.FromSlash(path))); err != nil {
		r.t.Fatal(err)
	}
}

// Commit stages everything and commits as Human; CommitAs picks the author.
// Both return the new commit's SHA.
func (r *Repo) Commit(msg string) string { return r.CommitAs(Human, msg) }

func (r *Repo) CommitAs(email, msg string) string {
	r.t.Helper()
	r.gitAs(email, "add", "-A")
	r.gitAs(email, "commit", "--quiet", "--allow-empty", "-m", msg)
	return r.gitAs(email, "rev-parse", "HEAD")
}
